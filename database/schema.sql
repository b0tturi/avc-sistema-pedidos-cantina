-- TEMA 4: SISTEMA DE PEDIDOS DE CANTINA
-- Banco: avc_cantina

CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL CHECK (LENGTH(TRIM(nome)) > 0),
    email VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL CHECK (LENGTH(TRIM(nome)) > 0),
    preco NUMERIC(10,2) NOT NULL CHECK (preco >= 0),
    estoque_disponivel INTEGER NOT NULL CHECK (estoque_disponivel >= 0)
);

CREATE TABLE pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id) ON DELETE RESTRICT,
    produto_id BIGINT NOT NULL REFERENCES produtos(id) ON DELETE RESTRICT,
    preco_registrado NUMERIC(10,2) NOT NULL CHECK (preco_registrado >= 0),
    data_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    situacao VARCHAR(15) NOT NULL DEFAULT 'ATIVO'
        CHECK (situacao IN ('ATIVO', 'CANCELADO'))
);

CREATE INDEX idx_pedidos_cliente ON pedidos(cliente_id);
CREATE INDEX idx_pedidos_produto ON pedidos(produto_id);

